import { useEffect, useMemo, useState } from 'react'
import { getAnalysis } from './services/api'
import MetricCard from './components/MetricCard'
import GenerationChart from './components/GenerationChart'
import ErrorChart from './components/ErrorChart'
import './styles/app.css'

function fmt(value) {
  return value == null ? '—' : Number(value).toLocaleString(undefined, { maximumFractionDigits: 0 })
}

export default function App() {
  const [data, setData] = useState(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  useEffect(() => {
    getAnalysis().then(setData).catch(e => setError(e.message)).finally(() => setLoading(false))
  }, [])

  const latest = useMemo(() => data?.latestForecast?.filter(x => x.actualGeneration != null).slice(-1)[0], [data])
  const period = data?.period

  return (
    <div className="app-shell">
      <header className="topbar">
        <div className="brand"><span className="brand-mark">W</span><div><strong>WindWatch</strong><span>Forecast intelligence</span></div></div>
        <div className="header-meta"><span>GB • January 2026</span><span className="live-dot">● Live data source</span></div>
      </header>

      <main className="container">
        <section className="hero">
          <div>
            <p className="eyebrow">DAY-AHEAD PROCUREMENT SUPPORT</p>
            <h1>Know the wind you can plan around.</h1>
            <p className="hero-copy">Compare Elexon's wind forecasts with actual generation and quantify forecast uncertainty before procurement decisions are made.</p>
          </div>
          <div className="decision-card">
            <span>Latest decision-support forecast</span>
            <strong>{latest ? `${fmt(latest.generation)} MW` : '—'}</strong>
            <small>{latest ? new Date(latest.startTime).toUTCString() : 'Loading…'}</small>
          </div>
        </section>

        {loading && <div className="state-card">Loading January 2026 Elexon data…</div>}
        {error && <div className="state-card error-state"><strong>Data request failed.</strong><br />{error}<br /><small>Check that the Python backend is running and can reach Elexon.</small></div>}

        {data && !error && <>
          <section className="metrics-grid">
            <MetricCard label="Mean Absolute Error" value={fmt(data.summary.mae)} suffix=" MW" />
            <MetricCard label="RMSE" value={fmt(data.summary.rmse)} suffix=" MW" />
            <MetricCard label="Mean Error" value={fmt(data.summary.meanError)} suffix=" MW" />
            <MetricCard label="Matched delivery hours" value={fmt(data.summary.matchedIntervals)} />
          </section>

          <section className="panel">
            <div className="panel-heading"><div><p className="eyebrow">FORECAST PERFORMANCE</p><h2>Forecast vs actual wind generation</h2></div><span className="badge">January 2026</span></div>
            <GenerationChart data={data.comparison} />
          </section>

          <section className="two-col">
            <div className="panel"><div className="panel-heading"><div><p className="eyebrow">ERROR PROFILE</p><h2>Where forecasts missed</h2></div></div><ErrorChart data={data.comparison} /></div>
            <div className="panel insight-panel"><p className="eyebrow">DECISION CONTEXT</p><h2>What this means</h2><div className="insight"><span>01</span><p><strong>Forecast</strong> shows the expected wind contribution for each 30-minute delivery interval.</p></div><div className="insight"><span>02</span><p><strong>Actual</strong> shows what was ultimately generated by wind.</p></div><div className="insight"><span>03</span><p><strong>Error</strong> is Actual − Forecast. Positive means generation exceeded the forecast.</p></div><div className="insight"><span>04</span><p><strong>MAE</strong> summarizes the typical size of forecast misses in MW.</p></div></div>
          </section>

          <section className="panel table-panel">
            <div className="panel-heading"><div><p className="eyebrow">LATEST DAY-AHEAD VIEW</p><h2>Forecast intervals</h2></div><span className="source">Source: Elexon BMRS</span></div>
            <div className="table-scroll"><table><thead><tr><th>Delivery time</th><th>Published</th><th>Forecast</th><th>Actual</th><th>Error</th></tr></thead><tbody>{data.latestForecast.slice(0, 48).map((row, i) => <tr key={`${row.startTime}-${i}`}><td>{new Date(row.startTime).toLocaleString('en-GB', { dateStyle: 'medium', timeStyle: 'short', timeZone: 'UTC' })} UTC</td><td>{new Date(row.publishTime).toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit', timeZone: 'UTC' })} UTC</td><td>{fmt(row.generation)} MW</td><td>{row.actualGeneration == null ? '—' : `${fmt(row.actualGeneration)} MW`}</td><td className={row.error > 0 ? 'positive' : row.error < 0 ? 'negative' : ''}>{row.error == null ? '—' : `${fmt(row.error)} MW`}</td></tr>)}</tbody></table></div>
          </section>

          <footer>Data period: {period?.start} → {period?.end} • Elexon BMRS FUELHH + WINDFOR • This portal is an analytical decision-support prototype.</footer>
        </>}
      </main>
    </div>
  )
}
